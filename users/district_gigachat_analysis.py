def enrich_district_report_with_ai(
    *,
    exam_type: str,
    stats: dict[str, Any],
    report_kind: str = "gia_summary",
    draft_insights: list[str] | None = None,
    draft_recommendations: list[str] | None = None,
    draft_conclusions: list[str] | None = None,
    draft_executive_summary: list[str] | None = None,
    extra_context: str = "",
    payload: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """
    Обогащает районные отчёты через GigaChat.
    Для gia_summary, info_stat, analytic_note, school_comparison и management (ЕГЭ/ОГЭ) — утверждённые промпты.
    """
    exam_type = _resolve_exam_type({"exam_type": exam_type})
    draft = {
        "insights": list(draft_insights or []),
        "recommendations": list(draft_recommendations or []),
        "conclusions": list(draft_conclusions or []),
        "executive_summary": list(draft_executive_summary or []),
    }
    fallback: dict[str, Any] = {key: list(value) for key, value in draft.items()}
    fallback["report_sections"] = []

    ai_result = _generate_district_report_ai(
        exam_type,
        stats,
        report_kind,
        draft,
        extra_context,
        payload=payload,
    )
    if not isinstance(ai_result, dict):
        return fallback

    if report_kind == "gia_summary" and exam_type in {"ege", "oge"}:
        return _normalize_gia_summary_ai_result(ai_result, fallback)
    if report_kind == "info_stat" and exam_type in {"ege", "oge"}:
        return _normalize_info_stat_ai_result(ai_result, fallback)
    if report_kind == "analytic_note" and exam_type in {"ege", "oge"}:
        return _normalize_analytic_note_ai_result(ai_result, fallback, exam_type=exam_type)
    if report_kind == "school_comparison" and exam_type in {"ege", "oge"}:
        return _normalize_school_comparison_ai_result(ai_result, fallback, exam_type=exam_type)
    if report_kind == "management" and exam_type == "oge":
        return _normalize_oge_management_ai_result(ai_result, fallback)
    if report_kind == "management" and exam_type == "ege":
        return _normalize_ege_management_ai_result(ai_result, fallback)

    return {
        "insights": _merge_text_list(
            ai_result.get("insights") if isinstance(ai_result.get("insights"), list) else None,
            fallback["insights"],
        ),
        "recommendations": _merge_text_list(
            ai_result.get("recommendations") if isinstance(ai_result.get("recommendations"), list) else None,
            fallback["recommendations"],
        ),
        "conclusions": _merge_text_list(
            ai_result.get("conclusions") if isinstance(ai_result.get("conclusions"), list) else None,
            fallback["conclusions"],
        ),
        "executive_summary": _merge_text_list(
            ai_result.get("executive_summary") if isinstance(ai_result.get("executive_summary"), list) else None,
            fallback["executive_summary"],
        ),
        "report_sections": [],
    }


