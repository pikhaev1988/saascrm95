def _setup(doc: Document) -> None:
    section = doc.sections[0]
    section.top_margin = Cm(1.8)
    section.bottom_margin = Cm(1.8)
    section.left_margin = Cm(2.2)
    section.right_margin = Cm(1.8)
    styles = doc.styles["Normal"]
    styles.font.name = "Times New Roman"
    styles.font.size = Pt(12)
    styles.font.color.rgb = INK
    styles._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    pf = styles.paragraph_format
    pf.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    pf.space_after = Pt(6)


def _p(doc, text="", *, bold=False, size=12, center=False, italic=False, space_after=6):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.line_spacing = 1.15
    if center:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(text)
    run.bold = bold
    run.italic = italic
    run.font.size = Pt(size)
    run.font.name = "Times New Roman"
    run.font.color.rgb = INK
    return p


def _h(doc, text, size=16):
    _p(doc, text, bold=True, size=size, center=True, space_after=10)


def save(doc: Document, name: str) -> Path:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / name
    doc.save(path)
    school_names = {
        "01_Pismo_shkole.docx",
        "02_Opisanie_platformy.docx",
        "03_Spravka_IB.docx",
        "04_Dogovor_5_let.docx",
        "05_Akt.docx",
        "06_Pamyatka_buhgalterii.docx",
    }
    if name in school_names:
        from users.legal import SCHOOL_DOCUMENTS_DIR

        SCHOOL_DOCUMENTS_DIR.mkdir(parents=True, exist_ok=True)
        dest = SCHOOL_DOCUMENTS_DIR / name
        dest.write_bytes(path.read_bytes())
    return path


