def get_subject_model(subject: str) -> SubjectExpertModel:
    from apps.vpr.expert_analysis.competences import normalize_subject

    key = normalize_subject(subject)
    if key in MODELS:
        return MODELS[key]
    for name, model in MODELS.items():
        if name in key or key in name:
            return model
    return DEFAULT_MODEL
