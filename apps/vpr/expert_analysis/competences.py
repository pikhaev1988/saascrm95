def normalize_subject(subject: str) -> str:
    text = (subject or "").strip().lower().replace("ё", "е")
    aliases = {
        "иностранный язык (английский)": "английский язык",
        "иностранный язык": "иностранный язык",
        "англ. язык": "английский язык",
        "литературное чтение на родном языке": "литературное чтение",
        "русский родной язык": "русский язык",
    }
    return aliases.get(text, text)


def competences_for_subject(subject: str) -> tuple[CompetenceModel, ...]:
    key = normalize_subject(subject)
    if key in SUBJECT_COMPETENCES:
        return SUBJECT_COMPETENCES[key]
    for name, models in SUBJECT_COMPETENCES.items():
        if name in key or key in name:
            return models
    return DEFAULT_COMPETENCES


def _haystacks_from_analysis(analysis) -> list[tuple[str, float | None]]:
    """(текст для матчинга, процент выполнения)."""
    items: list[tuple[str, float | None]] = []
    for row in analysis.topic_rows or []:
        topic = (getattr(row, "topic", None) or "").strip()
        if topic in PLACEHOLDER_TOPICS:
            continue
        pct = getattr(row, "avg_completion_percent", None)
        items.append((topic.lower(), float(pct) if pct is not None else None))
    for row in analysis.skill_rows or []:
        skill = (getattr(row, "checked_skill", None) or "").strip()
        if skill in PLACEHOLDER_SKILLS:
            continue
        pct = getattr(row, "avg_completion_percent", None)
        items.append((skill.lower(), float(pct) if pct is not None else None))
    for row in analysis.task_rows or []:
        parts = [
            str(row.get("topic") or ""),
            str(row.get("checked_skill") or ""),
            str(row.get("program_section") or ""),
        ]
        text = " ".join(p for p in parts if p).strip().lower()
        if not text:
            continue
        pct = row.get("completion_percent")
        items.append((text, float(pct) if pct is not None else None))
    return items


def analyze_competences(analysis, subject: str) -> list[CompetenceInsight]:
    models = competences_for_subject(subject)
    haystacks = _haystacks_from_analysis(analysis)
    insights: list[CompetenceInsight] = []

    for model in models:
        matched: list[tuple[str, float]] = []
        for text, pct in haystacks:
            if not model.keywords or model.keywords == ("",):
                continue
            if any(kw and kw in text for kw in model.keywords):
                if pct is not None:
                    matched.append((text[:80], pct))
        if model.keywords == ("",):
            # default competence: use overall topic averages
            matched = [(t[:80], p) for t, p in haystacks if p is not None][:12]

        if not matched:
            insights.append(
                CompetenceInsight(
                    name=model.name,
                    status="insufficient_data",
                    status_label="недостаточно данных каталога",
                    evidence=[],
                    conclusion=(
                        f"По компетенции «{model.name}» прямых сопоставлений с каталогом "
                        f"недостаточно; вывод строится по общему профилю предмета."
                    ),
                )
            )
            continue

        avg = sum(p for _, p in matched) / len(matched)
        evidence = [f"«{t}» ({p:.0f}%)" for t, p in matched[:4]]

        if avg >= 75:
            status, label, phrase = "formed", "сформирована", model.formed_phrase
        elif avg >= 60:
            status, label, phrase = "partial", "частично сформирована", model.formed_phrase
        else:
            status, label, phrase = "weak", "требует развития", model.weak_phrase

        insights.append(
            CompetenceInsight(
                name=model.name,
                status=status,
                status_label=label,
                evidence=evidence,
                conclusion=f"Компетенция «{model.name}» {label}: {phrase}.",
            )
        )
    return insights
